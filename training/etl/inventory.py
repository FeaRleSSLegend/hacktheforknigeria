def describe(p: Path) -> str:
    if p.suffix == ".xlsx":
        wb = openpyxl.load_workbook(p, read_only=True, data_only=True)
        return "; ".join(f"`{ws.title}` {ws.max_row}x{ws.max_column}" for ws in wb.worksheets)
    if p.suffix == ".csv":
        df = pd.read_csv(p, header=None, dtype=str)
        return f"{df.shape[0]} lines x {df.shape[1]} columns (including header)"
    return f"{p.stat().st_size} bytes"


def main():
    warnings.filterwarnings("ignore")
    lines = ["# Inventory of training/data", "", "Generated by training/etl/inventory.py. Raw files are read-only.", "",
             "| File | Size | Contents | Role |", "|---|---|---|---|"]
    problems = []
    for name, role in EXPECTED.items():
        p = RAW / name
        if not p.exists():
            problems.append(f"{name}: missing")
            lines.append(f"| {name} | - | MISSING | {role} |")
            continue
        try:
            desc = describe(p)
        except Exception as e:  # report any read failure, then stop
            problems.append(f"{name}: unreadable ({type(e).__name__}: {e})")
            desc = f"UNREADABLE: {type(e).__name__}"
        lines.append(f"| {name} | {p.stat().st_size} | {desc} | {role} |")
    extra = sorted(str(f.relative_to(RAW)).replace("\\", "/") for f in RAW.rglob("*") if f.is_file()
                   and str(f.relative_to(RAW)).replace("\\", "/") not in EXPECTED)
    lines += ["", f"Unexpected files: {', '.join(extra) or 'none'}", "", "## Findings", "",
              "- All expected files open. PhyFoodComp opens normally with food names intact, so salvage.py was not run.",
              "- WAFCT phytate: sheet `02 Components` says PHYTCPP is mg/100 g EP and the values match that "
              "(raw cowpea 779 mg; PhyFoodComp anion-exchange median for raw cowpea 752 mg). The 'looks like g' "
              "impression came from `wafct_selected.csv`, whose `phytate_mg` column holds the alpha-linolenic acid "
              "column (one column to the left). See training/reports/wafct_selected_diff.csv.",
              "- PulsesDM sheet 05 reuses FoodID PIS017_DM for two different pea foods; not one of our crops.",
              "- PulsesDM covers cowpea (generic, Brazil, India, Nigeria), pigeon pea (generic, India, Nigeria) and "
              "bambara (generic). No soybean, African yam bean or jack bean."]
    if problems:
        lines += ["", "## Problems", ""] + [f"- {p}" for p in problems]
    REPORTS.mkdir(parents=True, exist_ok=True)
    (REPORTS / "inventory.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[inventory] {len(EXPECTED) - len(problems)} of {len(EXPECTED)} expected files readable")
    if problems:
        print("\n".join(problems))
        raise SystemExit(1)


if __name__ == "__main__":
    main()
